export function ui(
  locale: Locale,
  key: UiKey,
  values: Record<string, string | number> = {},
) {
  return dictionaries[locale][key].replace(/\{([a-z]+)\}/g, (token, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : token,
  );
}
